// Writes web/config.js (gitignored) for local dev: the dev Convex URL from .env.local. Locally the game
// loads assets from web/assets (PACKS = false) and Google sign-in is optional, for syncing saves.
// The hosted site gets its own config from tools/build_site.mjs.
const fs = require('fs'), path = require('path');
const env = fs.existsSync(path.join(__dirname, '../.env.local')) ? fs.readFileSync(path.join(__dirname, '../.env.local'), 'utf8') : '';
const url = (env.match(/^CONVEX_URL=(.*)$/m) || [])[1]?.trim() || '';
fs.writeFileSync(path.join(__dirname, '../web/config.js'), `// generated by tools/write_config.cjs (do not commit)\nexport const CONVEX_URL = ${JSON.stringify(url)};\nexport const PACKS = false;\n`);
console.log('web/config.js ->', url || '(no Convex; cloud saves off)');
