// Writes web/config.js (gitignored) for local dev: the dev Convex URL from .env.local and the dev access key
// from .env.access.dev. The deployed site gets its own config from tools/build_site.cjs.
const fs = require('fs'), path = require('path');
const read = f => fs.existsSync(path.join(__dirname, '..', f)) ? fs.readFileSync(path.join(__dirname, '..', f), 'utf8') : '';
const url = (read('.env.local').match(/^CONVEX_URL=(.*)$/m) || [])[1]?.trim() || '';
const key = (read('.env.access.dev').match(/^ACCESS_KEY=(.*)$/m) || [])[1]?.trim() || '';
const out = `// generated by tools/write_config.cjs (do not commit)\nexport const CONVEX_URL = ${JSON.stringify(url)};\nexport const ACCESS_KEY = ${JSON.stringify(key)};\nexport const DEFAULT_EMAIL = '';\n`;
fs.writeFileSync(path.join(__dirname, '../web/config.js'), out);
console.log('web/config.js ->', url || '(no Convex; cloud saves off)', key ? '(with access key)' : '(no key)');
