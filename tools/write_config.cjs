// Writes web/config.js from .env.local (CONVEX_URL), so the static site knows its Convex deployment.
const fs = require('fs'), path = require('path');
const env = fs.existsSync(path.join(__dirname, '../.env.local')) ? fs.readFileSync(path.join(__dirname, '../.env.local'), 'utf8') : '';
const url = (env.match(/^CONVEX_URL=(.*)$/m) || [])[1]?.trim() || '';
fs.writeFileSync(path.join(__dirname, '../web/config.js'), `// generated by tools/write_config.cjs\nexport const CONVEX_URL = ${JSON.stringify(url)};\n`);
console.log('web/config.js ->', url || '(no Convex; cloud saves off)');
